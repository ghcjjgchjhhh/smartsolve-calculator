interface LanguageContextType {
  currentLanguage: AppLanguage;
  setLanguage: (code: string) => void;
  t: (key: string, fallback?: string) => string;
  isLanguageModalOpen: boolean;
  setIsLanguageModalOpen: (open: boolean) => void;
}

const LanguageContext = createContext<LanguageContextType>({
  currentLanguage: APP_LANGUAGES[0],
  setLanguage: () => {},
  t: (_k, fb) => fb || '',
  isLanguageModalOpen: false,
  setIsLanguageModalOpen: () => {},
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentCode, setCurrentCode] = useState<string>(() => {
    try {
      const saved = localStorage.getItem('smartsolve_app_language');
      if (saved && APP_LANGUAGES.some((l) => l.code === saved)) {
        return saved;
      }
      // Check browser language
      const navLang = (navigator.language || 'en').toLowerCase();
      const match = APP_LANGUAGES.find((l) => l.code === navLang || navLang.startsWith(l.code));
      if (match) return match.code;
    } catch {}
    return 'en';
  });

  const [isLanguageModalOpen, setIsLanguageModalOpen] = useState(false);

  const setLanguage = (code: string) => {
    setCurrentCode(code);
    try {
      localStorage.setItem('smartsolve_app_language', code);
      const chosen = APP_LANGUAGES.find((l) => l.code === code) || APP_LANGUAGES[0];

      // Sync voice settings in localStorage
      try {
        const raw = localStorage.getItem('smartsolve_chat_voice_settings');
        const parsed = raw ? JSON.parse(raw) : {};
        parsed.language = chosen.voiceCode;
        localStorage.setItem('smartsolve_chat_voice_settings', JSON.stringify(parsed));
      } catch {}

      window.dispatchEvent(
        new CustomEvent('smartsolve_language_changed', {
          detail: { code, language: chosen },
        })
      );
    } catch {}
  };

  const currentLanguage =
    APP_LANGUAGES.find((l) => l.code === currentCode) || APP_LANGUAGES[0];

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[currentCode] || TRANSLATIONS['en'];
    return langDict[key] || TRANSLATIONS['en']?.[key] || fallback || key;
  };

  useEffect(() => {
    if (currentLanguage.direction === 'rtl') {
      document.documentElement.dir = 'rtl';
    } else {
      document.documentElement.dir = 'ltr';
    }
  }, [currentLanguage]);

  return (
    <LanguageContext.Provider
      value={{
        currentLanguage,
        setLanguage,
        t,
        isLanguageModalOpen,
        setIsLanguageModalOpen,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useAppLanguage = () => useContext(LanguageContext);
